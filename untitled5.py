def plot_confusion_matrix(y_true, y_pred, class_names: list,
                           save_path: str = "confusion_matrix.png"):
    cm = confusion_matrix(y_true.argmax(axis=1), y_pred.argmax(axis=1))
    cm_norm = cm.astype("float") / cm.sum(axis=1, keepdims=True)

    plt.figure(figsize=(10, 8))
    sns.heatmap(cm_norm, annot=True, fmt=".2f", cmap="Blues",
                xticklabels=class_names, yticklabels=class_names,
                linewidths=0.5)
    plt.title("Normalised Confusion Matrix", fontsize=14, fontweight="bold")
    plt.xlabel("Predicted"); plt.ylabel("True")
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()
    print(f"Saved → {save_path}")


def evaluate_model(model: Model, X_test, y_test, label_encoder: LabelEncoder):
    """Full evaluation with metrics, confusion matrix, and per-class report."""
    loss, acc = model.evaluate(X_test, y_test, verbose=0)
    print(f"\n{'='*50}")
    print(f"  TEST ACCURACY : {acc*100:.2f}%")
    print(f"  TEST LOSS     : {loss:.4f}")
    print(f"{'='*50}\n")

    y_pred = model.predict(X_test, verbose=0)
    class_names = label_encoder.classes_

    print("Per-Class Report:")
    print(classification_report(
        y_test.argmax(axis=1),
        y_pred.argmax(axis=1),
        target_names=class_names
    ))

    plot_confusion_matrix(y_test, y_pred, class_names)
    return y_pred


# ─────────────────────────────────────────────
#   REAL-TIME INFERENCE
# ─────────────────────────────────────────────
def predict_emotion(model: Model, audio_path: str,
                    label_encoder: LabelEncoder,
                    max_len: int,
                    use_full_features: bool = False) -> dict:
    """
    Predict emotion for a single audio file.

    Returns:
        dict with keys: 'emotion', 'confidence', 'probabilities'
    """
    signal = load_audio(audio_path)
    feat = (extract_features if use_full_features else extract_mfcc_only)(signal)

    # Pad/trim
    T, F = feat.shape
    if T >= max_len:
        feat = feat[:max_len]
    else:
        feat = np.vstack([feat, np.zeros((max_len - T, F))])

    X = feat[np.newaxis, ...]  # (1, T, F)
    probs = model.predict(X, verbose=0)[0]

    emotion_idx = probs.argmax()
    return {
        "emotion": label_encoder.classes_[emotion_idx],
        "confidence": float(probs[emotion_idx]),
        "probabilities": {
            label_encoder.classes_[i]: float(probs[i])
            for i in range(len(label_encoder.classes_))
        }
    }


