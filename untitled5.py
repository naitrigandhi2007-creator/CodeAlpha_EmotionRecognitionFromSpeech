def build_cnn_lstm(input_shape: tuple, num_classes: int) -> Model:
    """
    CNN-LSTM hybrid model:
      Conv1D layers extract local temporal patterns →
      Bidirectional LSTM captures long-range dependencies →
      Dense classifier
    """
    inputs = Input(shape=input_shape, name="audio_features")

    # ── CNN blocks ──────────────────────────────
    x = Conv1D(64, kernel_size=3, padding="same", activation="relu")(inputs)
    x = BatchNormalization()(x)
    x = MaxPooling1D(pool_size=2)(x)
    x = Dropout(0.2)(x)

    x = Conv1D(128, kernel_size=3, padding="same", activation="relu")(x)
    x = BatchNormalization()(x)
    x = MaxPooling1D(pool_size=2)(x)
    x = Dropout(0.2)(x)

    x = Conv1D(256, kernel_size=3, padding="same", activation="relu")(x)
    x = BatchNormalization()(x)
    x = MaxPooling1D(pool_size=2)(x)
    x = Dropout(0.2)(x)

    # ── Bidirectional LSTM ───────────────────────
    x = Bidirectional(LSTM(128, return_sequences=True))(x)
    x = Dropout(0.3)(x)
    x = Bidirectional(LSTM(64, return_sequences=False))(x)
    x = Dropout(0.3)(x)

    # ── Classifier head ─────────────────────────
    x = Dense(256, activation="relu")(x)
    x = BatchNormalization()(x)
    x = Dropout(0.4)(x)
    x = Dense(128, activation="relu")(x)
    x = Dropout(0.3)(x)
    outputs = Dense(num_classes, activation="softmax", name="emotion")(x)

    model = Model(inputs, outputs, name="CNN_BiLSTM")
    return model


def build_cnn_only(input_shape: tuple, num_classes: int) -> Model:
    """Pure CNN model using global average pooling — fast and effective."""
    inputs = Input(shape=input_shape)

    x = Conv1D(64,  3, padding="same", activation="relu")(inputs)
    x = BatchNormalization()(x)
    x = MaxPooling1D(2)(x)
    x = Dropout(0.2)(x)

    x = Conv1D(128, 3, padding="same", activation="relu")(x)
    x = BatchNormalization()(x)
    x = MaxPooling1D(2)(x)
    x = Dropout(0.2)(x)

    x = Conv1D(256, 3, padding="same", activation="relu")(x)
    x = BatchNormalization()(x)
    x = MaxPooling1D(2)(x)
    x = Dropout(0.2)(x)

    x = Conv1D(512, 3, padding="same", activation="relu")(x)
    x = BatchNormalization()(x)
    x = GlobalAveragePooling1D()(x)

    x = Dense(256, activation="relu")(x)
    x = Dropout(0.4)(x)
    x = Dense(128, activation="relu")(x)
    x = Dropout(0.3)(x)
    outputs = Dense(num_classes, activation="softmax")(x)

    return Model(inputs, outputs, name="CNN_Only")


def build_lstm_only(input_shape: tuple, num_classes: int) -> Model:
    """Pure Bidirectional LSTM model."""
    inputs = Input(shape=input_shape)

    x = Bidirectional(LSTM(128, return_sequences=True, dropout=0.2))(inputs)
    x = Bidirectional(LSTM(128, return_sequences=True, dropout=0.2))(x)
    x = Bidirectional(LSTM(64,  return_sequences=False, dropout=0.2))(x)

    x = Dense(256, activation="relu")(x)
    x = Dropout(0.4)(x)
    x = Dense(128, activation="relu")(x)
    x = Dropout(0.3)(x)
    outputs = Dense(num_classes, activation="softmax")(x)

    return Model(inputs, outputs, name="BiLSTM_Only")


def build_transformer(input_shape: tuple, num_classes: int,
                       num_heads: int = 4, ff_dim: int = 128, num_layers: int = 3) -> Model:
    """
    Transformer encoder for speech emotion — cutting-edge approach.
    Multi-Head Self-Attention over time-steps.
    """
    inputs = Input(shape=input_shape)

    x = Dense(128, activation="relu")(inputs)  # project features → d_model=128

    for _ in range(num_layers):
        # Multi-Head Attention
        attn_out = MultiHeadAttention(num_heads=num_heads, key_dim=32)(x, x)
        x = LayerNormalization(epsilon=1e-6)(Add()([x, attn_out]))
        # Feed-Forward
        ff = Dense(ff_dim, activation="relu")(x)
        ff = Dense(128)(ff)
        x = LayerNormalization(epsilon=1e-6)(Add()([x, ff]))
        x = Dropout(0.1)(x)

    x = GlobalAveragePooling1D()(x)
    x = Dense(128, activation="relu")(x)
    x = Dropout(0.3)(x)
    outputs = Dense(num_classes, activation="softmax")(x)

    return Model(inputs, outputs, name="Transformer_Encoder")


