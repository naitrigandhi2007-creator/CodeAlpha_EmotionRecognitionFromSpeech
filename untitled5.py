def generate_synthetic_dataset(n_samples: int = 400, n_classes: int = 6,
                                time_steps: int = 130, n_features: int = 120):
    """
    Generate synthetic data to run the full pipeline without a real dataset.
    Replace this with load_ravdess() / load_tess() / load_emodb() for real training.
    """
    print("⚠  Using SYNTHETIC data for demonstration.")
    print("   Replace with load_ravdess() for real emotion recognition.\n")
    emotions = ["happy", "sad", "angry", "fearful", "neutral", "disgust"][:n_classes]
    X, y = [], []
    for i in range(n_samples):
        cls = i % n_classes
        # Different frequency / amplitude patterns per class
        t = np.linspace(0, 1, time_steps)
        signal = (
            np.sin(2 * np.pi * (cls + 1) * t * 3)
            + 0.3 * np.random.randn(time_steps)
        )
        feat = np.tile(signal[:, None], (1, n_features)) + 0.1 * np.random.randn(time_steps, n_features)
        X.append(feat)
        y.append(emotions[cls])
    return np.array(X), y


