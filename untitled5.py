#   PAD / TRIM SEQUENCES
# ─────────────────────────────────────────────
def pad_sequences(data: list, max_len: int = None) -> np.ndarray:
    """Zero-pad or trim all feature matrices to the same time length."""
    if max_len is None:
        max_len = max(x.shape[0] for x in data)
    padded = []
    for x in data:
        T, F = x.shape
        if T >= max_len:
            padded.append(x[:max_len])
        else:
            pad = np.zeros((max_len - T, F))
            padded.append(np.vstack([x, pad]))
    return np.array(padded)  # (N, max_len, F)


