def load_audio(file_path: str, sr: int = SAMPLE_RATE, duration: float = DURATION):
    """Load audio file and pad/trim to fixed duration."""
    signal, _ = librosa.load(file_path, sr=sr, duration=duration)
    target_length = sr * duration
    if len(signal) < target_length:
        signal = np.pad(signal, (0, target_length - len(signal)))
    else:
        signal = signal[:target_length]
    return signal


def extract_features(signal: np.ndarray, sr: int = SAMPLE_RATE) -> np.ndarray:
    """
    Extract a rich feature vector from an audio signal.

    Features extracted:
      - MFCCs (40 coefficients) + delta + delta-delta → shape (40, T, 3)
      - Mel Spectrogram                               → shape (128, T)
      - Chroma STFT                                   → shape (12, T)
      - Spectral Contrast                             → shape (7, T)
      - Zero Crossing Rate                            → shape (1, T)
      - RMS Energy                                    → shape (1, T)

    Returns concatenated feature matrix of shape (T, F) for sequence models.
    """
    # MFCCs
    mfccs = librosa.feature.mfcc(y=signal, sr=sr, n_mfcc=N_MFCC,
                                  n_fft=N_FFT, hop_length=HOP_LENGTH)
    mfccs_delta = librosa.feature.delta(mfccs)
    mfccs_delta2 = librosa.feature.delta(mfccs, order=2)

    # Mel Spectrogram (log-scale)
    mel_spec = librosa.feature.melspectrogram(y=signal, sr=sr, n_mels=N_MELS,
                                               n_fft=N_FFT, hop_length=HOP_LENGTH)
    mel_spec_db = librosa.power_to_db(mel_spec, ref=np.max)

    # Chroma
    chroma = librosa.feature.chroma_stft(y=signal, sr=sr,
                                          n_fft=N_FFT, hop_length=HOP_LENGTH)

    # Spectral Contrast
    contrast = librosa.feature.spectral_contrast(y=signal, sr=sr,
                                                  n_fft=N_FFT, hop_length=HOP_LENGTH)

    # Zero Crossing Rate
    zcr = librosa.feature.zero_crossing_rate(signal, hop_length=HOP_LENGTH)

    # RMS Energy
    rms = librosa.feature.rms(y=signal, hop_length=HOP_LENGTH)

    # Normalise each feature independently
    def norm(x):
        std = x.std(axis=1, keepdims=True)
        std[std == 0] = 1
        return (x - x.mean(axis=1, keepdims=True)) / std

    features = np.vstack([
        norm(mfccs),          # (40, T)
        norm(mfccs_delta),    # (40, T)
        norm(mfccs_delta2),   # (40, T)
        norm(mel_spec_db),    # (128, T)
        norm(chroma),         # (12, T)
        norm(contrast),       # (7, T)
        norm(zcr),            # (1, T)
        norm(rms),            # (1, T)
    ])                        # → (269, T)

    return features.T         # → (T, 269)  time-steps × features


def extract_mfcc_only(signal: np.ndarray, sr: int = SAMPLE_RATE) -> np.ndarray:
    """
    Lightweight MFCC-only extraction (40 + delta + delta2 = 120 features).
    Faster training for quick experiments.
    """
    mfccs = librosa.feature.mfcc(y=signal, sr=sr, n_mfcc=N_MFCC,
                                  n_fft=N_FFT, hop_length=HOP_LENGTH)
    delta = librosa.feature.delta(mfccs)
    delta2 = librosa.feature.delta(mfccs, order=2)
    features = np.concatenate([mfccs, delta, delta2], axis=0)  # (120, T)
    # Normalize
    features = (features - features.mean()) / (features.std() + 1e-8)
    return features.T  # (T, 120)


